def build_script(source, output):
    data = source.read_bytes()
    count = struct.unpack_from("<H", data, 0x62)[0] // 2
    first = struct.unpack_from("<I", data, 0x5C)[0]
    string_offset = data.rfind(b"@FileName")
    table_offset = data.rfind(struct.pack("<H", first), 0, string_offset)
    assert table_offset >= 0 and table_offset + count * 2 == string_offset
    assert struct.unpack_from("<H", data, 0x60)[0] == table_offset & 0xFFFF
    values = []
    previous = 0
    page = 0
    for index in range(count):
        low = struct.unpack_from("<H", data, table_offset + 2 * index)[0]
        if index and low < previous:
            page += 0x10000
        values.append(page + low)
        previous = low
    assert values[0] == first
    assert all(values[i] <= values[i + 1] for i in range(count - 1))
    assert values[-1] < table_offset < string_offset < len(data)
    trailer = struct.pack("<6I", MAGIC, 1, table_offset, string_offset, count, len(data))
    result = data + struct.pack("<%dI" % count, *values) + trailer
    output.write_bytes(result)
    return {"source_size": len(data), "size": len(result), "function_count": count,
            "function_table": table_offset, "string_table": string_offset,
            "richard_function": 71, "richard_offset": values[71],
            "voice_tags": len(re.findall(rb"#\d+v", data)),
            "sha256": hashlib.sha256(result).hexdigest()}


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "ed6_win3_DX9.exe"
    original = source.read_bytes()
    data, image_base, sections = load_pe(source)
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    section_count = struct.unpack_from("<H", data, pe + 6)[0]
    optional_size = struct.unpack_from("<H", data, pe + 20)[0]
    section_alignment, file_alignment = struct.unpack_from("<II", data, pe + 56)
    section_table = pe + 24 + optional_size
    new_header = section_table + section_count * 40
    assert new_header + 40 <= min(s["raw"] for s in sections)
    new_rva = align(max(s["rva"] + s["virtual_size"] for s in sections), section_alignment)
    raw = align(len(data), file_alignment)
    asm = function_code(image_base + new_rva)
    code = asm.finish()
    logging = logging_code(image_base + new_rva + len(code), image_base + new_rva)
    code += logging.finish()
    asm.labels.update(logging.labels)
    assert len(code) < 0x3000
    raw_size = align(max(len(code), 0x5000 + 8 * BUFFER_SIZE), file_alignment)
    virtual_size = raw_size
    patched = bytearray(original)
    if len(patched) < raw:
        patched.extend(b"\0" * (raw - len(patched)))
    header = struct.pack("<8sIIIIIIHHI", b".snx\0\0\0\0", virtual_size, new_rva,
                         raw_size, raw, 0, 0, 0, 0, 0xE0000020)
    assert len(header) == 40
    patched[new_header:new_header + 40] = header
    struct.pack_into("<H", patched, pe + 6, section_count + 1)
    struct.pack_into("<I", patched, pe + 80, new_rva + align(virtual_size, section_alignment))
    code_size = struct.unpack_from("<I", patched, pe + 28)[0]
    struct.pack_into("<I", patched, pe + 28, code_size + raw_size)
    struct.pack_into("<I", patched, pe + 88, 0)
    patched.extend(code)
    patched.extend(b"\0" * (raw_size - len(code)))
    patches = []

    def patch(va, expected, replacement):
        if isinstance(expected, str):
            expected = bytes.fromhex(expected)
        section = next(s for s in sections if image_base + s["rva"] <= va < image_base + s["rva"] + len(s["data"]))
        offset = section["raw"] + va - image_base - section["rva"]
        assert patched[offset:offset + len(expected)] == expected, (hex(va), patched[offset:offset + len(expected)].hex())
        assert len(replacement) <= len(expected)
        replacement = replacement.ljust(len(expected), b"\x90")
        patched[offset:offset + len(expected)] = replacement
        patches.append({"va": va, "original": expected.hex(), "replacement": replacement.hex()})

    def jump(va, expected, target):
        expected = bytes.fromhex(expected)
        relative = target - (va + 5)
        patch(va, expected, b"\xE9" + struct.pack("<i", relative))

